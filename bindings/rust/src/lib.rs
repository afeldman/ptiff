//! Idiomatic Rust bindings to libptiff via the language-agnostic C ABI
//! (`libptiff_c`, see `bindings/c`). This crate never links libptiff's C++ API
//! directly; it talks only to the stable `extern "C"` surface, exactly like the
//! Go, Python and Ruby bindings do.
//!
//! # Linking
//!
//! Point `PTIFF_C_LIB_DIR` at the directory containing `libptiff_c` (and
//! optionally `PTIFF_LIB_DIR` at the `libptiff` dir for the transitive shared
//! dependency), then:
//!
//! ```bash
//! PTIFF_C_LIB_DIR=/path/to/build/.../bindings/c \
//! PTIFF_LIB_DIR=/path/to/build/libptiff \
//! cargo test
//! ```

use std::ffi::{CStr, CString};
use std::os::raw::{c_double, c_int};
use std::path::Path;

// Raw `extern "C"` FFI declarations generated by `bindgen` directly from the
// C ABI headers under `bindings/c` (see `build.rs`). Never hand-edit this file
// or the manual-FFI duplication it replaces: the C headers are the single
// source of truth.
#[allow(
    non_camel_case_types,
    non_snake_case,
    non_upper_case_globals,
    dead_code,
    clippy::all
)]
mod ffi {
    include!(concat!(env!("OUT_DIR"), "/ptiff_ffi.rs"));
}

