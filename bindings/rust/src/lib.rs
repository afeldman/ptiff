/// RAII wrapper around a heap-owned write-side `ptiff::Sink` (see
/// `bindings/c/ptiff_pixel_bridge.h`). Dropping it flushes the underlying
/// writer via `ptiff_sink_close`.
///
/// The image must be tiled (`has_tile_info` set), otherwise the C ABI rejects
/// the descriptor — use [`ImageDescriptorBuilder::tile`].
pub struct Sink {
    raw: *mut SinkHandle,
}

impl Drop for Sink {
    fn drop(&mut self) {
        unsafe { ffi::ptiff_sink_close(self.raw) }
    }
}

impl Sink {
    /// Creates a TIFF/BigTIFF file at `path` for writing a single tiled image
    /// described by `builder`. `builder` **must** have `tile` set (a tiled
    /// layout is required for TIFF tile I/O).
    ///
    /// # Errors
    ///
    /// Returns [`CreateError`] if the C ABI could not create the sink (e.g. a
    /// non-tiled or otherwise invalid descriptor).
    pub fn create(
        path: impl AsRef<Path>,
        builder: ImageDescriptorBuilder,
    ) -> Result<Sink, CreateError> {
        let path_str = path.as_ref().to_str().ok_or(CreateError)?;
        let c_path = CString::new(path_str).map_err(|_| CreateError)?;

        let desc = builder.to_ffi();
        let raw = unsafe { ffi::ptiff_sink_create(c_path.as_ptr(), &desc) };
        if raw.is_null() {
            return Err(CreateError);
        }
        Ok(Sink { raw })
    }

    /// Creates a TIFF/BigTIFF file at `path` for writing a single tiled image
    /// described by `builder`, persisting `camera`'s calibration as
    /// `ptiff.camera.*` metadata (see [`Camera::pinhole`]). `builder`
    /// **must** have `tile` set.
    ///
    /// # Errors
    ///
    /// Returns [`CreateError`] if the C ABI could not create the sink (e.g. a
    /// NULL camera or an invalid descriptor).
    pub fn create_with_camera(
        path: impl AsRef<Path>,
        builder: ImageDescriptorBuilder,
        camera: &Camera,
    ) -> Result<Sink, CreateError> {
        let path_str = path.as_ref().to_str().ok_or(CreateError)?;
        let c_path = CString::new(path_str).map_err(|_| CreateError)?;

        let desc = builder.to_ffi();
        let cam = camera.to_ffi();
        let raw = unsafe { ffi::ptiff_sink_create_camera(c_path.as_ptr(), &desc, &cam) };
        if raw.is_null() {
            return Err(CreateError);
        }
        Ok(Sink { raw })
    }

    /// Tile grid columns at level 0.
    pub fn tile_columns(&self) -> u32 {
        unsafe { ffi::ptiff_sink_tile_columns(self.raw) }
    }

    /// Tile grid rows at level 0.
    pub fn tile_rows(&self) -> u32 {
        unsafe { ffi::ptiff_sink_tile_rows(self.raw) }
    }

    /// Byte size of one written tile's pixel data. Edge tiles are TIFF-padded
    /// to this uniform size.
    pub fn tile_byte_size(&self) -> usize {
        unsafe { ffi::ptiff_sink_tile_byte_size(self.raw) }
    }

    /// Writes one tile of raw, uncompressed pixel data to grid cell
    /// (`column`, `row`). `buffer` must be exactly `self.tile_byte_size()`
    /// bytes (the C ABI returns `InvalidArgument` on a mismatch).
    ///
    /// # Errors
    ///
    /// Returns a [`WriteError`] carrying the negative C ABI error code (e.g.
    /// `OutOfRange` for an out-of-grid tile index, or `InvalidArgument` for a
    /// buffer size mismatch).
    pub fn write_tile(&self, column: u32, row: u32, buffer: &[u8]) -> Result<(), WriteError> {
        let rc = unsafe {
            ffi::ptiff_sink_write_tile(self.raw, column, row, buffer.as_ptr(), buffer.len())
        };
        if rc != 0 {
            return Err(WriteError(rc));
        }
        Ok(())
    }
}

/// An error opening or reading a [`Source`]. The raw value is the negative C
/// ABI error code (see `bindings/c` `ptiff_error_code`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ReadError(pub i32);

impl ReadError {
    /// Human-friendly description, mirroring `ptiff::ErrorCode`.
    pub fn as_str(self) -> &'static str {
        match -self.0 {
            0 => "not implemented",
            1 => "invalid argument",
            2 => "out of range",
            3 => "not found",
            _ => "unknown",
        }
    }
}

impl std::fmt::Display for ReadError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{} (code {})", self.as_str(), self.0)
    }
}

impl std::error::Error for ReadError {}

/// RAII wrapper around a heap-owned read-side `ptiff::Source` (see
/// `bindings/c/ptiff_pixel_bridge.h`). Dropping it releases the underlying
/// reader via `ptiff_source_close`.
///
/// A source is a live handle over an open TIFF/BigTIFF file's primary image,
/// ready for tile/strip reads — the pixel-read counterpart of [`Sink`]. Both
/// tiled and striped images are exposed as a uniform tile grid via
/// [`Source::tile_columns`]/[`Source::tile_rows`].
pub struct Source {
    raw: *mut SourceHandle,
}

impl Drop for Source {
    fn drop(&mut self) {
        unsafe { ffi::ptiff_source_close(self.raw) }
    }
}

impl Source {
    /// Opens the primary image in the TIFF/BigTIFF file at `path` for pixel
    /// reading.
    ///
    /// # Errors
    ///
    /// Returns [`ReadError`] when the file cannot be opened or is not a valid
    /// TIFF/BigTIFF.
    pub fn open(path: impl AsRef<Path>) -> Result<Source, ReadError> {
        let path_str = path
            .as_ref()
            .to_str()
            .ok_or(ReadError(-(ErrorCode::InvalidArgument as i32)))?;
        let c_path =
            CString::new(path_str).map_err(|_| ReadError(-(ErrorCode::InvalidArgument as i32)))?;

        let mut err: c_int = 0;
        let raw = unsafe { ffi::ptiff_source_open(c_path.as_ptr(), &mut err) };
        if raw.is_null() {
            return Err(ReadError(if err != 0 { err } else { -1 }));
        }
        Ok(Source { raw })
    }

    /// Fills an [`ImageDescriptor`] with the opened image's metadata (same
    /// fields `ptiff_open_path` fills).
    ///
    /// # Errors
    ///
    /// Returns a [`ReadError`] for a NULL source/descriptor.
    pub fn descriptor(&self) -> Result<ImageDescriptor, ReadError> {
        let mut desc = ImageDescriptor {
            width: 0,
            height: 0,
            pixel_type: 0,
            channel_count: 0,
            has_gsd: 0,
            gsd: 0.0,
            has_tile_info: 0,
            tile_info: TileInfo::default(),
            has_compression: 0,
            compression: 0,
        };
        let rc = unsafe { ffi::ptiff_source_descriptor(self.raw, &mut desc) };
        if rc != 0 {
            return Err(ReadError(rc));
        }
        Ok(desc)
    }

    /// Converts the source's descriptor into an [`ImageDescriptorBuilder`] so
    /// the same layout can be recreated, e.g. for a [`Sink`] write side.
    /// GSD/compression are best-effort (the read ABI does not surface them).
    pub fn descriptor_builder(&self) -> Result<ImageDescriptorBuilder, ReadError> {
        let desc = self.descriptor()?;
        let mut b = ImageDescriptorBuilder::new(desc.width, desc.height, unsafe {
            std::mem::transmute::<c_int, PixelType>(desc.pixel_type)
        })
        .channel_count(desc.channel_count);
        if desc.has_tile_info != 0 {
            b = b.tile(desc.tile_info.tile_width, desc.tile_info.tile_height);
        }
        Ok(b)
    }

    /// Tile grid columns at level 0. For a non-tiled image this is the strip
    /// count (a single strip → 1).
    pub fn tile_columns(&self) -> u32 {
        unsafe { ffi::ptiff_source_tile_columns(self.raw) }
    }

    /// Tile grid rows at level 0.
    pub fn tile_rows(&self) -> u32 {
        unsafe { ffi::ptiff_source_tile_rows(self.raw) }
    }

    /// Byte size of one decoded tile's pixel data (edge/strip tiles are
    /// TIFF-padded to this uniform size).
    pub fn tile_byte_size(&self) -> usize {
        unsafe { ffi::ptiff_source_tile_byte_size(self.raw) }
    }

    /// Reads one decoded tile/strip at grid cell (`column`, `row`) into
    /// `buffer`. `buffer` must be at least [`Source::tile_byte_size`] bytes.
    ///
    /// # Errors
    ///
    /// Returns a [`ReadError`] carrying the negative C ABI error code (e.g.
    /// `OutOfRange` for an out-of-grid index, or `InvalidArgument` for a too
    /// small buffer).
    pub fn read_tile(&self, column: u32, row: u32, buffer: &mut [u8]) -> Result<usize, ReadError> {
        let mut bytes_read: usize = 0;
        let rc = unsafe {
            ffi::ptiff_source_read_tile(
                self.raw,
                column,
                row,
                buffer.as_mut_ptr(),
                buffer.len(),
                &mut bytes_read,
            )
        };
        if rc != 0 {
            return Err(ReadError(rc));
        }
        Ok(bytes_read)
    }
}

