    #[test]
    fn source_reads_back_sink_image() {
        // Write a 64x32 UInt8, 32x16-tiled image (2x2 = 4 tiles) with the
        // sink, then read all tiles back through the pixel-read Source API.
        let path = temp_tiff("source_roundtrip");
        let builder = ImageDescriptorBuilder::new(64, 32, PixelType::UInt8).tile(32, 16);

        let payload: Vec<u8> = (0..32 * 16).map(|i| i as u8).collect();
        {
            let sink = Sink::create(&path, builder).expect("create sink");
            for c in 0..2 {
                for r in 0..2 {
                    sink.write_tile(c, r, &payload).expect("write tile");
                }
            }
        } // drop(sink) -> flush

        let src = Source::open(&path).expect("open source");
        assert_eq!(src.tile_columns(), 2);
        assert_eq!(src.tile_rows(), 2);
        assert_eq!(src.tile_byte_size(), 32 * 16);

        let mut buf = vec![0u8; src.tile_byte_size()];
        for c in 0..2 {
            for r in 0..2 {
                let n = src.read_tile(c, r, &mut buf).expect("read tile");
                assert_eq!(n, payload.len());
                assert_eq!(&buf, &payload, "tile data must round-trip");
            }
        }

        // Converting the read descriptor to a builder reproduces the layout.
        let b = src.descriptor_builder().expect("descriptor_builder");
        assert_eq!(b.width, 64);
        assert_eq!(b.height, 32);
        assert_eq!(
            b.tile_info,
            Some(TileInfo {
                tile_width: 32,
                tile_height: 16
            })
        );

        // A too-small buffer is rejected with InvalidArgument (-1).
        let mut small = vec![0u8; src.tile_byte_size() - 1];
        assert_eq!(src.read_tile(0, 0, &mut small), Err(ReadError(-1)));
        // An out-of-grid index is OutOfRange (-2).
        let mut buf2 = vec![0u8; src.tile_byte_size()];
        assert_eq!(src.read_tile(9, 9, &mut buf2), Err(ReadError(-2)));

        let _ = std::fs::remove_file(&path);
    }

