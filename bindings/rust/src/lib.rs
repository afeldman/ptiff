/// Runtime version of the linked libptiff.
pub fn runtime_version() -> Version {
    unsafe { ffi::ptiff_runtime_version() }
}

/// Version libptiff's headers were compiled against.
pub fn compile_time_version() -> Version {
    unsafe { ffi::ptiff_compile_time_version() }
}

impl std::fmt::Display for Version {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}.{}.{}", self.major, self.minor, self.patch)
    }
}

/// Comma-space-separated list of registered backend names.
pub fn backend_names() -> Vec<String> {
    unsafe {
        let raw = ffi::ptiff_backend_names();
        if raw.is_null() {
            return Vec::new();
        }
        let s = CStr::from_ptr(raw).to_string_lossy().into_owned();
        // The C shim allocates with malloc; we must free it symmetrically.
        ffi::ptiff_free_string(raw);
        s.split(", ").map(|x| x.to_string()).collect()
    }
}

/// The process-wide logger singleton handle.
pub struct Logger;

impl Logger {
    /// Returns the shared logger instance.
    pub fn instance() -> Logger {
        Logger
    }

    pub fn set_level(&self, level: LogLevel) {
        unsafe { ffi::ptiff_logger_set_level(level as c_int) }
    }

    pub fn level(&self) -> LogLevel {
        unsafe { std::mem::transmute::<c_int, LogLevel>(ffi::ptiff_logger_level()) }
    }

    pub fn log(&self, level: LogLevel, message: &str) {
        let msg = CString::new(message).unwrap_or_default();
        unsafe { ffi::ptiff_logger_log(level as c_int, msg.as_ptr()) }
    }

    pub fn trace(&self, m: &str) {
        self.log(LogLevel::Trace, m)
    }
    pub fn debug(&self, m: &str) {
        self.log(LogLevel::Debug, m)
    }
    pub fn info(&self, m: &str) {
        self.log(LogLevel::Info, m)
    }
    pub fn warn(&self, m: &str) {
        self.log(LogLevel::Warn, m)
    }
    pub fn error(&self, m: &str) {
        self.log(LogLevel::Error, m)
    }
    pub fn critical(&self, m: &str) {
        self.log(LogLevel::Critical, m)
    }
}

/// A convenience builder for `ImageDescriptor`.
#[derive(Debug, Clone, Copy)]
pub struct ImageDescriptorBuilder {
    pub width: u32,
    pub height: u32,
    pub pixel_type: PixelType,
    pub channel_count: u32,
    pub gsd: Option<f64>,
    pub tile_info: Option<TileInfo>,
    pub compression: Option<CompressionKind>,
}

impl ImageDescriptorBuilder {
    pub fn new(width: u32, height: u32, pixel_type: PixelType) -> Self {
        Self {
            width,
            height,
            pixel_type,
            channel_count: 1,
            gsd: None,
            tile_info: None,
            compression: None,
        }
    }

    pub fn channel_count(mut self, n: u32) -> Self {
        self.channel_count = n;
        self
    }
    pub fn gsd(mut self, m: f64) -> Self {
        self.gsd = Some(m);
        self
    }
    pub fn tile(mut self, w: u32, h: u32) -> Self {
        self.tile_info = Some(TileInfo {
            tile_width: w,
            tile_height: h,
        });
        self
    }
    pub fn compression(mut self, k: CompressionKind) -> Self {
        self.compression = Some(k);
        self
    }

    fn to_ffi(self) -> ImageDescriptor {
        ImageDescriptor {
            width: self.width,
            height: self.height,
            pixel_type: self.pixel_type as c_int,
            channel_count: self.channel_count,
            has_gsd: self.gsd.is_some() as c_int,
            gsd: self.gsd.unwrap_or(0.0),
            has_tile_info: self.tile_info.is_some() as c_int,
            tile_info: self.tile_info.unwrap_or_default(),
            has_compression: self.compression.is_some() as c_int,
            compression: self.compression.map(|k| k as c_int).unwrap_or(0),
        }
    }

    pub fn build(self) -> Image {
        let desc = self.to_ffi();
        unsafe {
            let raw = ffi::ptiff_image_create(&desc);
            if raw.is_null() {
                panic!("ptiff_image_create failed");
            }
            Image { raw }
        }
    }
}

/// RAII wrapper around a heap-owned `ptiff::Image`.
pub struct Image {
    raw: *mut ImageHandle,
}

impl Drop for Image {
    fn drop(&mut self) {
        unsafe { ffi::ptiff_image_destroy(self.raw) }
    }
}

impl Image {
    pub fn width(&self) -> u32 {
        unsafe { ffi::ptiff_image_width(self.raw) }
    }
    pub fn height(&self) -> u32 {
        unsafe { ffi::ptiff_image_height(self.raw) }
    }
    pub fn pixel_type(&self) -> PixelType {
        unsafe { std::mem::transmute::<c_int, PixelType>(ffi::ptiff_image_pixel_type(self.raw)) }
    }
    pub fn channel_count(&self) -> u32 {
        unsafe { ffi::ptiff_image_channel_count(self.raw) }
    }

    pub fn gsd(&self) -> Option<f64> {
        unsafe {
            let mut out: c_double = 0.0;
            if ffi::ptiff_image_gsd(self.raw, &mut out) != 0 {
                Some(out)
            } else {
                None
            }
        }
    }

    pub fn tile_info(&self) -> Option<TileInfo> {
        unsafe {
            let mut out: TileInfo = TileInfo::default();
            if ffi::ptiff_image_tile_info(self.raw, &mut out) != 0 {
                Some(out)
            } else {
                None
            }
        }
    }

    pub fn compression(&self) -> Option<CompressionKind> {
        unsafe {
            let mut out: c_int = 0;
            if ffi::ptiff_image_compression(self.raw, &mut out) != 0 {
                Some(std::mem::transmute::<c_int, CompressionKind>(out))
            } else {
                None
            }
        }
    }
}

