    #[test]
    fn read_metadata_combines_file_fields_and_camera() {
        let fixture = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../scripts/samples/ptiff_interop_fixture.tif");
        let canonical = std::fs::canonicalize(&fixture)
            .unwrap_or_else(|_| panic!("fixture missing: {}", fixture.display()));

        let md = read_metadata(&canonical).expect("read_metadata(fixture)");
        assert_eq!(md.file.width, 128);
        assert_eq!(md.file.height, 128);
        assert_eq!(md.file.pixel_type, PixelType::UInt8);
        // The unified reader surfaces the extension fields and the camera.
        assert_eq!(md.field("ptiff.camera.model"), Some("pinhole"));
        assert_eq!(md.field("ptiff.spice.frame"), Some("IAU_MOON"));
        let cam = md.camera.expect("camera present");
        assert_eq!(cam.focal_length_x, 700.0);
    }

    #[test]
    fn read_metadata_plain_tiff_has_no_camera_or_fields() {
        // A plain (camera-less) tiled TIFF has an empty field list and no
        // camera; the unified reader must still succeed and report that.
        let path = temp_tiff("meta_plain");
        let builder = ImageDescriptorBuilder::new(16, 16, PixelType::UInt8).tile(16, 16);
        let sink = Sink::create(&path, builder).expect("create sink");
        sink.write_tile(0, 0, &vec![0u8; sink.tile_byte_size()])
            .expect("write tile");
        drop(sink);

        let md = read_metadata(&path).expect("read_metadata(plain)");
        assert_eq!(md.file.width, 16);
        assert!(
            md.fields.is_empty(),
            "expected no fields, got {:?}",
            md.fields
        );
        assert!(md.camera.is_none(), "expected no camera");
        assert_eq!(md.field("ptiff.camera.model"), None);

        let _ = std::fs::remove_file(&path);
    }

