/// Opens a TIFF/BigTIFF file with the C ABI's `ptiff_open_path` and returns
/// its primary image metadata.
///
/// # Errors
///
/// Returns the C ABI's negative `ptiff_*` error code wrapped in [`OpenError`]
/// when the file cannot be opened or read (e.g. `Error::NotFound`).
pub fn open_path(path: impl AsRef<Path>) -> Result<FileMetadata, OpenError> {
    let path_str = path
        .as_ref()
        .to_str()
        .ok_or(OpenError(-(ErrorCode::InvalidArgument as i32)))?;
    let c_path =
        CString::new(path_str).map_err(|_| OpenError(-(ErrorCode::InvalidArgument as i32)))?;

    let mut desc = ImageDescriptor {
        width: 0,
        height: 0,
        pixel_type: 0,
        channel_count: 0,
        has_gsd: 0,
        gsd: 0.0,
        has_tile_info: 0,
        tile_info: TileInfo::default(),
        has_compression: 0,
        compression: 0,
    };

    let rc = unsafe { ffi::ptiff_open_path(c_path.as_ptr(), &mut desc) };
    if rc != 0 {
        return Err(OpenError(rc));
    }

    Ok(FileMetadata {
        width: desc.width,
        height: desc.height,
        pixel_type: unsafe { std::mem::transmute::<c_int, PixelType>(desc.pixel_type) },
        channel_count: desc.channel_count,
        tile_info: if desc.has_tile_info != 0 {
            Some(desc.tile_info)
        } else {
            None
        },
    })
}

/// Opens a TIFF/BigTIFF file via the C ABI's `ptiff_open_path_fields` and
/// returns its flattened PTIFF extension fields decoded from the private tags
/// 65001-65005 (SPICE, camera geometry, CRS, scientific layers, provenance).
///
/// Keys carry the `ptiff.<domain>.<name>` shape (e.g. `"ptiff.spice.frame"`)
/// and the resulting vector is ordered lexicographically by key. Each element
/// is an owned `(key, value)` pair; the underlying C array is freed
/// automatically with `ptiff_fields_free`.
///
/// # Errors
///
/// Returns the C ABI's negative `ptiff_*` error code wrapped in [`OpenError`]
/// when the file cannot be opened or read (e.g. `Error::NotFound`).
pub fn open_path_fields(path: impl AsRef<Path>) -> Result<Vec<(String, String)>, OpenError> {
    let path_str = path
        .as_ref()
        .to_str()
        .ok_or(OpenError(-(ErrorCode::InvalidArgument as i32)))?;
    let c_path =
        CString::new(path_str).map_err(|_| OpenError(-(ErrorCode::InvalidArgument as i32)))?;

    let mut out: *mut Field = std::ptr::null_mut();
    let mut out_count: c_int = 0;

    let rc = unsafe { ffi::ptiff_open_path_fields(c_path.as_ptr(), &mut out, &mut out_count) };
    if rc != 0 {
        return Err(OpenError(rc));
    }

    let count = out_count as usize;
    let mut fields = Vec::with_capacity(count);
    if !out.is_null() {
        for i in 0..count {
            let f = unsafe { &*out.add(i) };
            let key = unsafe { CStr::from_ptr(f.key) }
                .to_string_lossy()
                .into_owned();
            let value = unsafe { CStr::from_ptr(f.value) }
                .to_string_lossy()
                .into_owned();
            fields.push((key, value));
        }
    }
    unsafe { ffi::ptiff_fields_free(out, out_count) };
    Ok(fields)
}

/// Structured camera calibration decoded from the `ptiff.camera.*` extension
/// fields of a TIFF/BigTIFF file. Carries the pinhole intrinsics, the
/// extrinsics (rotation quaternion + world translation), the ISO-8601
/// observation timestamp, and the three derived matrices K / [R|t] / P (all
/// row-major doubles). The projection `P = K * [R|t]` is computed in the C++
/// library.
#[derive(Debug, Clone)]
pub struct Camera {
    pub has_intrinsics: bool,
    pub focal_length_x: f64,
    pub focal_length_y: f64,
    pub principal_x: f64,
    pub principal_y: f64,
    /// 3x3 intrinsic calibration matrix K (row-major).
    pub intrinsics: [f64; 9],
    pub has_extrinsics: bool,
    pub rotation_w: f64,
    pub rotation_x: f64,
    pub rotation_y: f64,
    pub rotation_z: f64,
    pub position_x: f64,
    pub position_y: f64,
    pub position_z: f64,
    /// 3x4 extrinsic matrix [R | t] (row-major).
    pub extrinsics: [f64; 12],
    /// 3x4 projection matrix P = K * [R | t] (row-major).
    pub projection: [f64; 12],
    /// ISO-8601 UTC observation timestamp; empty when unset.
    pub timestamp: String,
    /// The camera model name, e.g. `"pinhole"`. Read from the
    /// `ptiff.camera.model` extension field when available; defaults to
    /// `"pinhole"` when constructing a [`Camera::pinhole`].
    pub model: String,
}

impl Camera {
    /// Constructs a camera calibration suitable for **writing** to a new file
    /// via [`Sink::create_with_camera`] from raw pinhole intrinsics and
    /// extrinsics. `timestamp` defaults to empty when `None`.
    ///
    /// Only the scalar fields (`focal_length_*`, `principal_*`,
    /// `rotation_*`, `position_*`) are persisted into the
    /// `ptiff.camera.*` metadata; the derived matrices `K`, `[R | t]` and
    /// `P = K * [R | t]` are computed by the C++ library on read and are left
    /// zero-filled here.
    #[allow(clippy::too_many_arguments)]
    pub fn pinhole(
        focal_length_x: f64,
        focal_length_y: f64,
        principal_x: f64,
        principal_y: f64,
        rotation_w: f64,
        rotation_x: f64,
        rotation_y: f64,
        rotation_z: f64,
        position_x: f64,
        position_y: f64,
        position_z: f64,
        timestamp: Option<String>,
    ) -> Camera {
        Camera {
            has_intrinsics: true,
            focal_length_x,
            focal_length_y,
            principal_x,
            principal_y,
            intrinsics: [0.0; 9],
            has_extrinsics: true,
            rotation_w,
            rotation_x,
            rotation_y,
            rotation_z,
            position_x,
            position_y,
            position_z,
            extrinsics: [0.0; 12],
            projection: [0.0; 12],
            timestamp: timestamp.unwrap_or_default(),
            model: "pinhole".to_string(),
        }
    }

    /// Converts this calibration into the C ABI `ptiff_camera` struct used by
    /// `ptiff_sink_create_camera` for writing.
    fn to_ffi(&self) -> ffi::ptiff_camera {
        let mut timestamp = [0i8; 64];
        let bytes = self.timestamp.as_bytes();
        let n = bytes.len().min(63);
        for (i, b) in bytes[..n].iter().enumerate() {
            timestamp[i] = *b as i8;
        }
        ffi::ptiff_camera {
            has_intrinsics: self.has_intrinsics as i32,
            focal_length_x: self.focal_length_x,
            focal_length_y: self.focal_length_y,
            principal_x: self.principal_x,
            principal_y: self.principal_y,
            intrinsics: [0.0; 9],
            has_extrinsics: self.has_extrinsics as i32,
            rotation_w: self.rotation_w,
            rotation_x: self.rotation_x,
            rotation_y: self.rotation_y,
            rotation_z: self.rotation_z,
            position_x: self.position_x,
            position_y: self.position_y,
            position_z: self.position_z,
            extrinsics: [0.0; 12],
            projection: [0.0; 12],
            timestamp,
        }
    }
}

/// Opens a TIFF/BigTIFF file at `path` and returns the structured camera
/// calibration decoded from its `ptiff.camera.*` extension fields (see
/// [`Camera`]).
///
/// # Errors
///
/// Returns the C ABI's negative `ptiff_*` error code wrapped in [`OpenError`]
/// when the file cannot be opened or read.
pub fn open_path_camera(path: impl AsRef<Path>) -> Result<Camera, OpenError> {
    let path_str = path
        .as_ref()
        .to_str()
        .ok_or(OpenError(-(ErrorCode::InvalidArgument as i32)))?;
    let c_path =
        CString::new(path_str).map_err(|_| OpenError(-(ErrorCode::InvalidArgument as i32)))?;

    let mut cam = ffi::ptiff_camera {
        has_intrinsics: 0,
        focal_length_x: 0.0,
        focal_length_y: 0.0,
        principal_x: 0.0,
        principal_y: 0.0,
        intrinsics: [0.0; 9],
        has_extrinsics: 0,
        rotation_w: 0.0,
        rotation_x: 0.0,
        rotation_y: 0.0,
        rotation_z: 0.0,
        position_x: 0.0,
        position_y: 0.0,
        position_z: 0.0,
        extrinsics: [0.0; 12],
        projection: [0.0; 12],
        timestamp: [0; 64],
    };

    let rc = unsafe { ffi::ptiff_open_path_camera(c_path.as_ptr(), &mut cam) };
    if rc != 0 {
        return Err(OpenError(rc));
    }

    let c_str = unsafe { CStr::from_ptr(cam.timestamp.as_ptr()) };

    // The C ABI struct has no camera-model slot; recover it from the
    // `ptiff.camera.model` extension field where present (default "pinhole").
    let model = open_path_fields(path)
        .ok()
        .and_then(|fields| {
            fields
                .iter()
                .find(|(k, _)| k == "ptiff.camera.model")
                .map(|(_, v)| v.clone())
        })
        .unwrap_or_else(|| "pinhole".to_string());

    Ok(Camera {
        has_intrinsics: cam.has_intrinsics != 0,
        focal_length_x: cam.focal_length_x,
        focal_length_y: cam.focal_length_y,
        principal_x: cam.principal_x,
        principal_y: cam.principal_y,
        intrinsics: cam.intrinsics,
        has_extrinsics: cam.has_extrinsics != 0,
        rotation_w: cam.rotation_w,
        rotation_x: cam.rotation_x,
        rotation_y: cam.rotation_y,
        rotation_z: cam.rotation_z,
        position_x: cam.position_x,
        position_y: cam.position_y,
        position_z: cam.position_z,
        extrinsics: cam.extrinsics,
        projection: cam.projection,
        timestamp: c_str.to_string_lossy().into_owned(),
        model,
    })
}

/// Full read-side metadata for an on-disk TIFF/BigTIFF file: the primary
/// image descriptor, the flattened PTIFF extension fields, and the structured
/// camera calibration (when present). A single [`read_metadata`] call returns
/// everything the idiomatic layer knows about a file in one go.
#[derive(Debug, Clone)]
pub struct Metadata {
    /// Primary image descriptor (width, height, pixel type, channels, tiles).
    pub file: FileMetadata,
    /// Flattened PTIFF extension fields as `(key, value)` pairs (keys carry
    /// the `ptiff.<domain>.<name>` shape), ordered lexicographically.
    pub fields: Vec<(String, String)>,
    /// Structured camera calibration; `None` when the file has neither
    /// intrinsics nor extrinsics.
    pub camera: Option<Camera>,
}

impl Metadata {
    /// Looks up a single flattened extension field by its fully qualified key
    /// (e.g. `"ptiff.spice.frame"`), returning `None` when absent. Mirrors the
    /// `field(key)` accessor of the Python binding.
    pub fn field(&self, key: &str) -> Option<&str> {
        self.fields
            .iter()
            .find(|(k, _)| k == key)
            .map(|(_, v)| v.as_str())
    }
}

/// Reads the complete read-side metadata of the TIFF/BigTIFF file at `path` in
/// a single call: [`FileMetadata`], the flattened `ptiff.<domain>.<name>`
/// extension fields, and the structured [`Camera`] (when present). This is the
/// one-stop "inspect a file" entry point, uniform with the `read_metadata`
/// tool of the MCP binding.
///
/// # Errors
///
/// Returns the C ABI's negative `ptiff_*` error code wrapped in [`OpenError`]
/// when the file cannot be opened or read.
pub fn read_metadata(path: impl AsRef<Path>) -> Result<Metadata, OpenError> {
    let file = open_path(&path)?;
    let fields = open_path_fields(&path)?;
    let camera = open_path_camera(&path)
        .ok()
        .filter(|c| c.has_intrinsics || c.has_extrinsics);
    Ok(Metadata {
        file,
        fields,
        camera,
    })
}

