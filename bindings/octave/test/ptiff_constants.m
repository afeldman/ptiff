function c = ptiff_constants()
%PTIFF_CONSTANTS  All ptiff SWIG enum constants as a struct.
%
%   Functions cannot dereference the SWIG namespace object ptiff.<CONST>, but
%   the SWIG module registers its constants as Octave global variables. This
%   helper reads them so test functions get plain numeric values. Call
%   ptiff() once first (the test runner does).
%
%   Returns a struct with one field per constant, e.g.
%       c.PTIFF_PIXEL_UINT8, c.PTIFF_LOG_ERROR, c.PTIFF_COMPRESSION_DEFLATE.
global PTIFF_ERROR_NOT_IMPLEMENTED PTIFF_ERROR_INVALID_ARGUMENT ...
  PTIFF_ERROR_OUT_OF_RANGE PTIFF_ERROR_NOT_FOUND PTIFF_ERROR_UNKNOWN ...
  PTIFF_LOG_TRACE PTIFF_LOG_DEBUG PTIFF_LOG_INFO PTIFF_LOG_WARN ...
  PTIFF_LOG_ERROR PTIFF_LOG_CRITICAL PTIFF_LOG_OFF ...
  PTIFF_PIXEL_UINT8 PTIFF_PIXEL_UINT16 PTIFF_PIXEL_UINT32 ...
  PTIFF_PIXEL_FLOAT32 PTIFF_PIXEL_FLOAT64 ...
  PTIFF_COMPRESSION_NONE PTIFF_COMPRESSION_LZW ...
  PTIFF_COMPRESSION_DEFLATE PTIFF_COMPRESSION_JPEG;

c = struct( ...
  'PTIFF_ERROR_NOT_IMPLEMENTED', PTIFF_ERROR_NOT_IMPLEMENTED, ...
  'PTIFF_ERROR_INVALID_ARGUMENT', PTIFF_ERROR_INVALID_ARGUMENT, ...
  'PTIFF_ERROR_OUT_OF_RANGE', PTIFF_ERROR_OUT_OF_RANGE, ...
  'PTIFF_ERROR_NOT_FOUND', PTIFF_ERROR_NOT_FOUND, ...
  'PTIFF_ERROR_UNKNOWN', PTIFF_ERROR_UNKNOWN, ...
  'PTIFF_LOG_TRACE', PTIFF_LOG_TRACE, ...
  'PTIFF_LOG_DEBUG', PTIFF_LOG_DEBUG, ...
  'PTIFF_LOG_INFO', PTIFF_LOG_INFO, ...
  'PTIFF_LOG_WARN', PTIFF_LOG_WARN, ...
  'PTIFF_LOG_ERROR', PTIFF_LOG_ERROR, ...
  'PTIFF_LOG_CRITICAL', PTIFF_LOG_CRITICAL, ...
  'PTIFF_LOG_OFF', PTIFF_LOG_OFF, ...
  'PTIFF_PIXEL_UINT8', PTIFF_PIXEL_UINT8, ...
  'PTIFF_PIXEL_UINT16', PTIFF_PIXEL_UINT16, ...
  'PTIFF_PIXEL_UINT32', PTIFF_PIXEL_UINT32, ...
  'PTIFF_PIXEL_FLOAT32', PTIFF_PIXEL_FLOAT32, ...
  'PTIFF_PIXEL_FLOAT64', PTIFF_PIXEL_FLOAT64, ...
  'PTIFF_COMPRESSION_NONE', PTIFF_COMPRESSION_NONE, ...
  'PTIFF_COMPRESSION_LZW', PTIFF_COMPRESSION_LZW, ...
  'PTIFF_COMPRESSION_DEFLATE', PTIFF_COMPRESSION_DEFLATE, ...
  'PTIFF_COMPRESSION_JPEG', PTIFF_COMPRESSION_JPEG);
end
